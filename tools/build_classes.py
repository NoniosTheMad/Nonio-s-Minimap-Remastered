"""Build the class framework data from src/classes.json (DESIGN 2.12, 6.3).

    python tools/build_classes.py

Writes into datapack/data/nonios/ (everything under a class/ or class/gen/ folder is regenerated; hand-written ability
code lives in function/class/<class>/ and is never touched):
  enchantment/class/<key>.json                   class enchantments (dynamic registry: server restart after changes)
  loot_table/class/<class>/[l<N>/]<item>.json    one item each (components set by set_components)
  advancement/class/use/<class>_<item>.json      right-click detection for items with a consumable component
  function/class/gen/<class>/*.mcfunction        apply, equip, strip, vision, vision_off, check (+ need_<item>, used_<item>)
  function/class/gen/*.mcfunction               dispatchers on the nx.class score + catalog (storage nonios:class)
"""
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "classes.json"
OUT = ROOT / "datapack" / "data" / "nonios"
HEADER = "# GENERATED by tools/build_classes.py from src/classes.json - do not edit\n"
ARMOR = {"armor.head", "armor.chest", "armor.legs", "armor.feet"}
EQUIP = ARMOR | {"weapon.offhand"}
HOLD_SECONDS = 60  # consumables longer than this are "hold to use" (using_item) instead of "use once" (consume_item)


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def fn(path, lines):
    write(OUT / "function" / f"{path}.mcfunction", HEADER + "".join(l + "\n" for l in lines))


def jtext(c):
    return json.dumps(c, ensure_ascii=False, separators=(",", ":"))


def item_components(cid, c, key, it):
    comp = dict(it.get("components", {}))
    tag = f"{cid}_{key}"
    comp["minecraft:custom_data"] = {"nx_cls": cid, "nx_item": tag, "nx_cls_item": True}
    ench = dict(comp.get("minecraft:enchantments", {}))
    ench["minecraft:vanishing_curse"] = 1  # class items never drop on death (keep_inventory off) - they are re-given
    if c["tier"] == "shop" and it["slot"] in ARMOR:
        ench["minecraft:binding_curse"] = 1  # shop classes lock their armour
    comp["minecraft:enchantments"] = ench
    comp.setdefault("minecraft:unbreakable", {})
    if "name" in it:
        comp["minecraft:custom_name"] = dict(it["name"], italic=False)
    lore = list(it.get("lore", []))
    tier = "shop class: lost on death" if c["tier"] == "shop" else "basic class"
    lore.append({"text": f"{c['name']['text']} · {tier}", "color": "dark_gray", "italic": False})
    comp["minecraft:lore"] = lore
    hidden = set(comp.get("minecraft:tooltip_display", {}).get("hidden_components", []))
    hidden |= {"minecraft:unbreakable", "minecraft:dyed_color"}
    comp["minecraft:tooltip_display"] = {"hidden_components": sorted(hidden)}
    return comp


def loot_table(it, comp):
    # 26.3 loot format: "modifier" (was "functions"), each with "type" (was "function"), single "condition" object
    mods = [{"type": "minecraft:set_components", "components": comp}]
    if it.get("count", 1) != 1:
        mods.append({"type": "minecraft:set_count", "count": it["count"]})
    cd = comp.get("minecraft:use_cooldown")
    if cd and cd.get("cooldown_group"):
        # demo "reset cooldowns": vanilla has no command to clear an item cooldown, so the re-given item moves to an
        # alternate cooldown group while nx.cls_cdalt is 1 (loot "this" = the player running /loot).
        mods.append({"type": "minecraft:set_components",
                     "components": {"minecraft:use_cooldown": dict(cd, cooldown_group=cd["cooldown_group"] + "_alt")},
                     "condition": {"type": "minecraft:entity_scores", "entity": "this",
                                   "scores": {"nx.cls_cdalt": {"min": 1}}}})
    return {"pools": [{"rolls": 1, "entries": [{"type": "minecraft:item", "name": it["id"], "modifier": mods}]}]}


def slot_match(tag):
    return f'*[minecraft:custom_data~{{nx_item:"{tag}"}}]'


def build():
    d = json.loads(SRC.read_text(encoding="utf-8"))
    classes = d["classes"]
    for sub in ("function/class/gen", "loot_table/class", "enchantment/class", "advancement/class/use"):
        shutil.rmtree(OUT / sub, ignore_errors=True)
    nums = [c["num"] for c in classes.values()]
    assert len(nums) == len(set(nums)) and min(nums) >= 1, "class nums must be unique and >= 1"

    disp = {k: [] for k in ("apply", "strip", "vision", "vision_off", "check", "tick", "purge")}
    catalog = []
    for cid, c in classes.items():
        n, g = c["num"], f"class/gen/{cid}"
        hooks = set(c.get("hooks", []))
        basic = c["tier"] == "basic"
        levels = c["levels"] if basic else {"": c["items"]}

        for key, e in c.get("enchantments", {}).items():
            write(OUT / "enchantment" / "class" / f"{key}.json", json.dumps(e, indent=1) + "\n")

        # ---- items: loot tables + equip function per level
        equip_fns = {}
        for lvl, items in levels.items():
            sub = f"l{lvl}/" if lvl else ""
            lines = []
            for key, it in items.items():
                comp = item_components(cid, c, key, it)
                write(OUT / "loot_table" / "class" / cid / f"{sub}{key}.json", json.dumps(loot_table(it, comp), indent=1) + "\n")
                table = f"nonios:class/{cid}/{sub}{key}"
                if it["slot"] in EQUIP:
                    lines.append(f'function nonios:class/stash {{slot:"{it["slot"]}"}}')
                    lines.append(f"loot replace entity @s {it['slot']} loot {table}")
                else:
                    lines.append(f"loot give @s loot {table}")
                if not basic:
                    _uses(cid, key, it, comp, hooks)
            name = f"{g}/equip" + (f"_l{lvl}" if lvl else "")
            fn(name, [f"# {cid}" + (f" level {lvl}" if lvl else "") + ": equipment (old armour/offhand goes back to the inventory)"] + lines)
            equip_fns[lvl] = name

        # ---- vision (post effects, stacking order)
        fx = c.get("vision", [])
        fn(f"{g}/vision_off", [f"posteffect remove @s {e}" for e in reversed(fx)] or ["# no vision"])
        fn(f"{g}/vision", ([f"function nonios:{g}/vision_off"] + [f"posteffect add @s {e}" for e in fx]) or ["# no vision"])

        # ---- apply
        lines = ["# as/at the player: become this class (strips the current one first)",
                 "function nonios:class/strip",
                 f"scoreboard players set @s nx.class {n}"]
        if basic:
            lines.append(f"scoreboard players set @s nx.cls_basic {n}")
            lines.append("function nonios:class/level")
            for lvl, name in equip_fns.items():
                lines.append(f"execute if score #lvl nx.cls_tmp matches {lvl} run function nonios:{name}")
        else:
            lines.append(f"function nonios:{equip_fns['']}")
        lines.append(f"function nonios:{g}/vision")
        if "on_apply" in hooks:
            lines.append(f"function nonios:class/{cid}/on_apply")
        lines.append(f"tellraw @s [{{\"text\":\"✦ You are now a \",\"color\":\"gray\"}},{jtext(c['name'])}"
                     + (',{"text":" (lost on death)","color":"dark_gray"}' if not basic else
                        ',{"text":" (level ","color":"dark_gray"},{"score":{"name":"#lvl","objective":"nx.cls_tmp"},"color":"dark_gray"},{"text":", back on every respawn)","color":"dark_gray"}')
                     + "]")
        lines.append("playsound minecraft:block.beacon.power_select player @s ~ ~ ~ 0.6 1.4")
        fn(f"{g}/apply", lines)

        # ---- strip (items are cleared by class/strip itself)
        lines = [f"function nonios:{g}/vision_off"] + [f"effect clear @s {e}" for e in c.get("clear_effects", [])]
        if "on_strip" in hooks:
            lines.append(f"function nonios:class/{cid}/on_strip")
        fn(f"{g}/strip", ["# as the player, before its class items are cleared"] + lines)

        # ---- check (shop classes keep their kit: re-equip / give back what went missing)
        if not basic:
            lines = ["# as/at the player, every second and right after a consumable class item was used"]
            for key, it in c["items"].items():
                tag, table = f"{cid}_{key}", f"nonios:class/{cid}/{key}"
                if it["slot"] in EQUIP:
                    lines.append(f"execute unless items entity @s {it['slot']} {slot_match(tag)} run function nonios:{g}/need_{key}")
                    fn(f"{g}/need_{key}", [f'kill @e[type=item,nbt={{Item:{{components:{{"minecraft:custom_data":{{nx_item:"{tag}"}}}}}}}}]',
                                           f"clear @s {slot_match(tag)}",
                                           f'function nonios:class/stash {{slot:"{it["slot"]}"}}',
                                           f"loot replace entity @s {it['slot']} loot {table}"])
                else:
                    lines.append(f"function nonios:{g}/need_{key}")
                    fn(f"{g}/need_{key}", [
                        f"# {key} must stay with its owner: missing from inventory/offhand/cursor/crafting grid -> back in hand",
                        f"execute if items entity @s container.* {slot_match(tag)} run return 0",
                        f"execute if items entity @s weapon.offhand {slot_match(tag)} run return 0",
                        f"execute if items entity @s player.cursor {slot_match(tag)} run return 0",
                        f"execute if items entity @s player.crafting.* {slot_match(tag)} run return 0",
                        f'kill @e[type=item,nbt={{Item:{{components:{{"minecraft:custom_data":{{nx_item:"{tag}"}}}}}}}}]',
                        f"execute unless items entity @s weapon.mainhand * run return run loot replace entity @s weapon.mainhand loot {table}",
                        f"loot give @s loot {table}"])
            fn(f"{g}/check", lines)
            disp["check"].append(f"execute if score @s nx.class matches {n} run return run function nonios:{g}/check")

        disp["apply"].append(f"execute if score @s nx.cls_req matches {n} run return run function nonios:{g}/apply")
        disp["strip"].append(f"execute if score @s nx.class matches {n} run return run function nonios:{g}/strip")
        disp["vision"].append(f"execute if score @s nx.class matches {n} run return run function nonios:{g}/vision")
        disp["vision_off"].append(f"execute if score @s nx.class matches {n} run return run function nonios:{g}/vision_off")
        disp["purge"].append(f'execute unless score @s nx.class matches {n} run clear @s *[minecraft:custom_data~{{nx_cls:"{cid}"}}]')
        if "tick" in hooks:
            disp["tick"].append(f"execute as @e[type=player,scores={{nx.class={n}}}] at @s run function nonios:class/{cid}/tick")
        catalog.append({"id": cid, "num": n, "tier": c["tier"], "price": c.get("price", 0), "name": c["name"], "blurb": c.get("blurb", "")})

    fn("class/gen/apply", ["# as/at the player: apply class number nx.cls_req"] + disp["apply"])
    fn("class/gen/strip", ["# as the player: undo the class-specific state of its current class"] + disp["strip"])
    fn("class/gen/vision", ["# as the player: (re)apply its class post effects"] + disp["vision"])
    fn("class/gen/vision_off", disp["vision_off"])
    fn("class/gen/check", ["# as/at a player with a shop class: kit integrity"] + disp["check"])
    fn("class/gen/purge", ["# as the player: delete class items of classes it does not have (stale copies, items picked up from others)"] + disp["purge"])
    fn("class/gen/tick", ["# per-tick class hooks (only players of that class)"] + disp["tick"])
    lost = [f'execute if score @s nx.class matches {c["num"]} run return run tellraw @s [{{"text":"☠ ","color":"dark_red"}},{jtext(c["name"])},{{"text":" is gone: {c.get("lost_msg", "shop classes die with you.")}","color":"gray"}}]'
            for c in classes.values() if c["tier"] == "shop"]
    fn("class/gen/lost", ["# as a player who just lost its shop class to death"] + lost)
    tier_lines = [f"execute if score @s nx.class matches {c['num']} run return {1 if c['tier'] == 'shop' else 0}"
                  for c in classes.values()]
    fn("class/gen/is_shop", ["# as the player: returns 1 if its current class is a shop class"] + tier_lines + ["return 0"])
    snbt = json.dumps(catalog, ensure_ascii=False)
    fn("class/gen/catalog", ["# class catalog for menus/shop: storage nonios:class catalog[] {id,num,tier,price,name,blurb}",
                             f"data modify storage nonios:class catalog set value {snbt}"])
    print("classes built:", ", ".join(classes))


def _uses(cid, key, it, comp, hooks):
    """Right-click detection for a consumable class item -> function class/<cid>/use_<key> (hand-written)."""
    cons = comp.get("minecraft:consumable")
    if not cons:
        return
    hold = cons.get("consume_seconds", 1.6) >= HOLD_SECONDS
    tag = f"{cid}_{key}"
    adv = f"nonios:class/use/{tag}"
    write(OUT / "advancement" / "class" / "use" / f"{tag}.json", json.dumps({
        "criteria": {"use": {"trigger": "minecraft:using_item" if hold else "minecraft:consume_item",
                             "conditions": {"item": {"predicates": {"minecraft:custom_data": {"nx_item": tag}}}}}},
        "rewards": {"function": f"nonios:class/gen/{cid}/used_{key}"}}, indent=1) + "\n")
    lines = [f"advancement revoke @s only {adv}"]
    if hold:
        lines.insert(0, "# fires every tick while right-click is held")
    else:
        lines.insert(0, "# fires when the use finishes: the item was consumed (survival), so it is given back next tick")
        lines.append("scoreboard players set @s nx.cls_restock 1")
    lines.append(f"execute at @s run function nonios:class/{cid}/use_{key}")
    fn(f"class/gen/{cid}/used_{key}", lines)


if __name__ == "__main__":
    build()
