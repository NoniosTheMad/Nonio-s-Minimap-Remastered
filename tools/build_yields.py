"""Build the coin yields per mined block from src/yields.json (feedback #36).

    python tools/build_yields.py

Writes (run on /reload via purse/load, and every tick via purse/player):
  datapack/data/nonios/function/purse/gen/yields.mcfunction  stat objectives nx.mn.<block> (mined) / nx.pl.<block> (placed)
      and the table: #<block> nx.coinval = coins per block in hundredths, #fortune_pct / #place_mult nx.coinval.
      Values are (re)written when #version nx.coinval differs from the source version, so /scoreboard tweaks
      survive a /reload but a new table replaces them.
  datapack/data/nonios/function/purse/gen/check.mcfunction   as a player: new mined/placed stats -> purse/mine/award|placed.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "yields.json"
OUT = ROOT / "datapack" / "data" / "nonios" / "function" / "purse" / "gen"
HEADER = "# GENERATED by tools/build_yields.py from src/yields.json - do not edit (edit src/yields.json, rebuild, /reload)\n"


def main():
    src = json.loads(SRC.read_text(encoding="utf-8"))
    ver, pct, fmax = int(src["version"]), int(src["fortune_pct"]), int(src["fortune_max"])
    blocks = src["blocks"]
    y = [HEADER,
         f"# coins per block in hundredths; Fortune +{pct}% per level; placing costs the value at Fortune {fmax}\n"]
    for b in blocks:
        assert b.replace("_", "").isalnum() and len(f"nx.mn.{b}") <= 64, b
        y.append(f"scoreboard objectives add nx.mn.{b} minecraft.mined:minecraft.{b}\n")
        y.append(f"scoreboard objectives add nx.pl.{b} minecraft.used:minecraft.{b}\n")
    y.append(f"execute if score #version nx.coinval matches {ver} run return 0\n")
    y.append(f"scoreboard players set #version nx.coinval {ver}\n")
    y.append(f"scoreboard players set #fortune_pct nx.coinval {pct}\n")
    y.append(f"scoreboard players set #place_mult nx.coinval {100 + pct * fmax}\n")
    for b, v in blocks.items():
        h = round(float(v) * 100)
        assert abs(h - float(v) * 100) < 1e-6 and h >= 0, f"{b}: {v} (resolution is 0.01 coins)"
        y.append(f"scoreboard players set #{b} nx.coinval {h}\n")
    c = [HEADER, "# as a player, every tick: new mined / placed stats -> coins (purse/mine/award, purse/mine/placed)\n"]
    for b in blocks:
        c.append(f'execute if score @s nx.mn.{b} matches 1.. run function nonios:purse/mine/award {{b:"{b}"}}\n')
        c.append(f'execute if score @s nx.pl.{b} matches 1.. run function nonios:purse/mine/placed {{b:"{b}"}}\n')
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "yields.mcfunction").write_text("".join(y), encoding="utf-8", newline="\n")
    (OUT / "check.mcfunction").write_text("".join(c), encoding="utf-8", newline="\n")
    print(f"{len(blocks)} blocks, version {ver} -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
