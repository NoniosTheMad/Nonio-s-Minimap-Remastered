"""Build the shop catalog from src/shop.json (V2 shop, gap inventory section 5).

    python tools/build_shop.py

Writes datapack/data/nonios/function/shop/catalog.mcfunction (run by shop/load on every /reload):
  storage nonios:shop items     flat list, button code 100 + index = buy items[index] (shop/buy). The classes from
                                src/classes.json are appended after these by class/gen/shop_items (tools/build_classes.py).
  storage nonios:shop sections  one entry per page: title, body (Shop Keeper line), items (buttons with their code n)
                                or classes:1 (the page lists the class entries of items).
Item entries in src/shop.json may also be references (resolved here, so prices keep one source):
  {"same": v2}                  a copy of the catalog item with that v2 id from an earlier page (V2 listed items twice).
  {"special": id}               an entry of src/specials.json (kind special: shop/buy_special runs its buy function).
  {"class": id, "name", "v2"}   a class of src/classes.json under another label (V2 "Monster Skull" = Monster); price,
                                blurb and icon from the class. alias 1 keeps it off the Classes page.
  storage nonios:shop menu      the first page's buttons (code 10 + section index).
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "shop.json"
SPECIALS = ROOT / "src" / "specials.json"
CLASSES = ROOT / "src" / "classes.json"
OUT = ROOT / "datapack" / "data" / "nonios" / "function" / "shop" / "catalog.mcfunction"
HEADER = "# GENERATED by tools/build_shop.py from src/shop.json - do not edit (edit src/shop.json, rebuild, /reload)\n"
ENCHANT_TIP = "Enchants the item in your hand."


def snbt(v):
    """JSON is valid SNBT for everything used here (quoted keys, ints, doubles, booleans, strings)."""
    return json.dumps(v, ensure_ascii=False, separators=(",", ":"))


def icon(path):
    kind, tex = path.split("/", 1)
    return {"items": "minecraft:items", "blocks": "minecraft:blocks"}[{"item": "items", "block": "blocks"}[kind]], f"minecraft:{kind}/{tex}"


def item_string(it):
    comp = it.get("components")
    if not comp:
        return it["id"]
    return it["id"] + "[" + ",".join(f"{k}={snbt(v)}" for k, v in comp.items()) + "]"


def no_quotes(*txt):
    for t in txt:
        assert '"' not in t and "\\" not in t, f"{t!r}: no double quotes/backslashes (shop dialog macro)"


def resolve(it, seen, specials, classes):
    """Expand a reference entry into (entry for storage items, button fields), or None for a plain catalog item."""
    if "same" in it:
        assert it["same"] in seen, f"same {it['same']}: no earlier item with that v2 id"
        return None, dict(seen[it["same"]])
    if "special" in it:
        sp = specials[it["special"]]
        no_quotes(sp["name"], sp.get("blurb", ""))
        e = {"name": sp["name"], "label": sp["name"], "kind": "special", "count": 1, "price": sp["price"], "v2": sp["v2"],
             "fn": sp["buy"], "charge": 1 if sp["charge"] else 0, "slot": 1 if sp["slot"] else 0}
        return e, {"label": sp["name"], "price": sp["price"], "atlas": sp["atlas"], "sprite": sp["sprite"], "blurb": sp.get("blurb", "")}
    if "class" in it:
        cid = it["class"]
        c = classes[cid]
        price = c.get("price", 0)
        no_quotes(it["name"], c.get("blurb", ""))
        e = {"name": c["name"]["text"], "label": it["name"], "class": cid, "num": c["num"], "count": 1, "price": price,
             "ptxt": f"{price}c" if price else "free", "confirm": 1 if c["shop"].get("confirm") else 0, "alias": 1, "v2": it["v2"]}
        return e, {"label": it["name"], "price": price, "atlas": c["shop"].get("atlas", "minecraft:items"),
                   "sprite": c["shop"]["sprite"], "blurb": c.get("blurb", "")}
    return None, None


def main():
    src = json.loads(SRC.read_text(encoding="utf-8"))
    specials = {sp["id"]: sp for sp in json.loads(SPECIALS.read_text(encoding="utf-8"))["items"]}
    classes = json.loads(CLASSES.read_text(encoding="utf-8"))["classes"]
    seen = {}  # v2 id -> catalog item (for "same")
    items, sections, menu = [], [], []
    for k, sec in enumerate(src["sections"]):
        atlas, sprite = icon(sec["icon"])
        menu.append({"label": [{"type": "object", "atlas": atlas, "sprite": sprite}, {"text": " " + sec["name"], "color": "gold"}],
                     "width": 150, "action": {"type": "minecraft:run_command", "command": f"trigger nx.shop set {10 + k}"}})
        out = {"name": sec["name"], "classes": 1 if sec.get("classes") else 0,
               "title": {"text": "Shop · " + sec["name"], "color": "gold", "bold": True},
               "body": {"type": "minecraft:plain_message", "width": 300,
                        "contents": [{"text": "Shop Keeper: ", "color": "red", "bold": True}, {"text": sec["line"], "color": "red"}]},
               "items": []}
        for it in sec.get("items", []):
            e, ref = resolve(it, seen, specials, classes)
            if ref is not None and e is not None:
                n = 100 + len(items)
                items.append(e)
                ref["blurb"] = ref["blurb"] + "\\n" if ref["blurb"] else ""
                out["items"].append(dict(ref, n=n))
                continue
            if ref is not None:
                it = ref
            seen.setdefault(it["v2"], it)
            kind = it.get("kind", "item")
            count = it.get("count", 1)
            label = it["name"] + (f" x{count}" if count > 1 else "")
            atlas, sprite = icon(it["icon"])
            blurb = it.get("blurb", ENCHANT_TIP if kind == "enchant" else "")
            e = {"name": it["name"], "label": label, "kind": kind, "count": count, "price": it["price"], "v2": it["v2"]}
            if kind == "item":
                e["item"] = item_string(it)
            elif kind == "enchant":
                e["ench"], e["lvl"] = it["ench"], it["lvl"]
            elif kind == "xp":
                e["lvl"] = it["lvl"]
            else:
                raise SystemExit(f"{it['name']}: unknown kind {kind}")
            if "chat" in it:
                e["chat"] = it["chat"]
            n = 100 + len(items)
            items.append(e)
            out["items"].append({"label": label, "price": it["price"], "atlas": atlas, "sprite": sprite,
                                 # backslash + n: ui/action inserts it inside a quoted string (a real newline would split the macro line)
                                 "blurb": blurb + "\\n" if blurb else "", "n": n})
        sections.append(out)
    lines = [HEADER,
             "# V2 catalog with V2 prices (the remaster's defaults). Button codes (trigger nx.shop): 1 = first page,\n",
             "# 10 + k = page k, 100 + i = buy items[i]. The classes (class/gen/shop_items) are appended to items last.\n",
             "data modify storage nonios:shop items set value []\n"]
    lines += [f"data modify storage nonios:shop items append value {snbt(e)}\n" for e in items]
    lines += ["data modify storage nonios:shop sections set value []\n"]
    lines += [f"data modify storage nonios:shop sections append value {snbt(s)}\n" for s in sections]
    lines += [f"data modify storage nonios:shop menu set value {snbt(menu)}\n",
              "# + the classes sold here (generated from src/classes.json by tools/build_classes.py)\n",
              "function nonios:class/gen/shop_items\n"]
    OUT.write_text("".join(lines), encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(ROOT)}: {len(items)} items in {len(sections)} sections")


if __name__ == "__main__":
    main()
