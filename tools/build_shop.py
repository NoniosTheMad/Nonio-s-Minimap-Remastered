"""Build the shop catalog from src/shop.json (shop v3: bulk buying, paged categories, scales to hundreds of items).

    python tools/build_shop.py                                   game catalog -> shop/catalog.mcfunction
    python tools/build_shop.py --extra demos/shop3/stress.json --out demos/shop3/datapack/data/demo/function/catalog_stress.mcfunction
                                                                  same + extra sections (demo stress test)

Writes storage nonios:shop (shop/catalog runs on every /reload via shop/load):
  items[i]   flat list, trigger nx.shop = 100 + i buys items[i] (shop/buy). The classes of src/classes.json are appended
             after these by class/gen/shop_items (tools/build_classes.py), in the order of src/classes.json.
  nodes[j]   the dialog screens. j = 0 is the home screen; trigger nx.shop = 10 + j opens node j (j >= 1, max 89).
             {name, up (parent node), upg (parent page holding this node), kind: "menu" | "items", pages: [[...] x <= 16]}
             menu pages hold ready-made category buttons; items pages hold entries {n, label, ncol, atlas, sprite,
             price, count, bulk, sl, unit, blurb} that shop/ui/entry turns into buttons (price x quantity mode, greyed if
             unaffordable).
Sections in src/shop.json may nest: a section with "sub" (list of sections) is a menu node (category -> subcategory).
Item entries may be references (resolved here, so prices keep one source):
  {"same": v2}                  a copy of the catalog item with that v2 id from an earlier page (V2 listed items twice).
  {"special": id}               an entry of src/specials.json (kind special: shop/buy_special runs its buy function).
  {"class": id, "name", "v2"}   a class of src/classes.json under another label (V2 "Monster Skull" = Monster); price,
                                blurb and icon from the class. alias 1 keeps it off the Classes page.
Bulk (kind item / xp): quantity modes x1 / x8 / x64 lots, or Stack = one full stack (sl = stack // count lots).
stack = max stack size (guessed from the id; "stack": N in src/shop.json overrides) for the free-space check.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "shop.json"
SPECIALS = ROOT / "src" / "specials.json"
CLASSES = ROOT / "src" / "classes.json"
OUT = ROOT / "datapack" / "data" / "nonios" / "function" / "shop" / "catalog.mcfunction"
SHOP_ITEMS = ROOT / "datapack" / "data" / "nonios" / "function" / "class" / "gen" / "shop_items.mcfunction"
HEADER = "# GENERATED by tools/build_shop.py from {src} - do not edit (edit the json, rebuild, /reload)\n"
PAGE = 16          # entries per screen (4 columns x 4 rows under the two control rows)
WIDTH = 120        # button width (shop/ui/* use the same)
ENCHANT_TIP = "Enchants the item in your hand."

ONE = re.compile(r"_(sword|pickaxe|axe|shovel|hoe|spear|helmet|chestplate|leggings|boots|bucket|boat|raft|bed|minecart|"
                 r"horse_armor|nautilus_armor)$|^minecraft:(bow|crossbow|trident|mace|shield|flint_and_steel|shears|fishing_rod|"
                 r"potion|splash_potion|lingering_potion|totem_of_undying|enchanted_book|saddle|elytra|cake|spyglass|brush|"
                 r"writable_book|written_book|music_disc_.*|carrot_on_a_stick|warped_fungus_on_a_stick|bundle|.*_bundle|"
                 r"debug_stick|knowledge_book|goat_horn|ominous_bottle|wolf_armor|turtle_helmet|.*_shulker_box|shulker_box)$")
SIXTEEN = re.compile(r"_(sign|hanging_sign|banner)$|^minecraft:(ender_pearl|snowball|egg|blue_egg|brown_egg|bucket|"
                     r"honey_bottle|armor_stand|wind_charge)$")


def snbt(v):
    """JSON is valid SNBT for everything used here (quoted keys, ints, doubles, booleans, strings)."""
    return json.dumps(v, ensure_ascii=False, separators=(",", ":"))


def icon(path):
    kind, tex = path.split("/", 1)
    return {"item": "minecraft:items", "block": "minecraft:blocks"}[kind], f"minecraft:{kind}/{tex}"


def item_string(it):
    comp = it.get("components")
    if not comp:
        return it["id"]
    return it["id"] + "[" + ",".join(f"{k}={snbt(v)}" for k, v in comp.items()) + "]"


def stack_size(it):
    if "stack" in it:
        return it["stack"]
    comp = it.get("components", {})
    if "minecraft:max_stack_size" in comp:
        return comp["minecraft:max_stack_size"]
    if ONE.search(it["id"]):
        return 1
    if SIXTEEN.search(it["id"]):
        return 16
    return 64


def no_quotes(*txt):
    for t in txt:
        assert '"' not in t and "\\" not in t, f"{t!r}: no double quotes/backslashes (shop dialog macro)"


def nl(t):
    # backslash + n: the ui macros paste it inside a quoted string (a real newline would split the macro line)
    return t + "\\n" if t else ""


def resolve(it, seen, specials, classes):
    """Expand a reference entry into (entry for storage items, button fields), or None for a plain catalog item."""
    if "same" in it:
        assert it["same"] in seen, f"same {it['same']}: no earlier item with that v2 id"
        return None, dict(seen[it["same"]])
    if "special" in it:
        sp = specials[it["special"]]
        no_quotes(sp["name"], sp.get("blurb", ""))
        e = {"name": sp["name"], "label": sp["name"], "kind": "special", "count": 1, "price": sp["price"], "v2": sp["v2"],
             "fn": sp["buy"], "charge": 1 if sp["charge"] else 0, "slot": 1 if sp["slot"] else 0,
             "atlas": sp["atlas"], "sprite": sp["sprite"], "ncol": sp.get("ncol", "white"), "bulk": 0}
        return e, {"label": sp["name"], "ncol": sp.get("ncol", "white"), "price": sp["price"], "count": 1, "bulk": 0, "sl": 1,
                   "atlas": sp["atlas"], "sprite": sp["sprite"], "unit": "", "blurb": nl(sp.get("blurb", ""))}
    if "class" in it:
        cid = it["class"]
        c = classes[cid]
        price = c.get("price", 0)
        no_quotes(it["name"], c.get("blurb", ""))
        atlas, sprite = c["shop"].get("atlas", "minecraft:items"), c["shop"]["sprite"]
        ncol = c["name"].get("color", "white")
        e = {"name": c["name"]["text"], "label": it["name"], "class": cid, "num": c["num"], "count": 1, "price": price,
             "confirm": 1 if c["shop"].get("confirm") else 0, "alias": 1, "v2": it["v2"],
             "atlas": atlas, "sprite": sprite, "ncol": ncol, "bulk": 0}
        return e, {"label": it["name"], "ncol": ncol, "price": price, "count": 1, "bulk": 0, "sl": 1, "atlas": atlas,
                   "sprite": sprite, "unit": "", "blurb": nl(c.get("blurb", ""))}
    return None, None


class Builder:
    def __init__(self):
        self.specials = {sp["id"]: sp for sp in json.loads(SPECIALS.read_text(encoding="utf-8"))["items"]}
        self.classes = json.loads(CLASSES.read_text(encoding="utf-8"))["classes"]
        self.seen = {}      # v2 id -> catalog item (for "same")
        self.items = []     # storage items
        self.nodes = [None]  # storage nodes; 0 = home (filled last)
        self.class_pages = []  # nodes that list the classes (filled once the item count is known)

    def entry(self, it):
        """One catalog item (or reference) -> page entry; appends to items when it is a new item."""
        e, ref = resolve(it, self.seen, self.specials, self.classes)
        if ref is not None and e is not None:
            n = 100 + len(self.items)
            self.items.append(e)
            return dict(ref, n=n)
        if ref is not None:
            it = ref
        self.seen.setdefault(it.get("v2", id(it)), it)
        kind = it.get("kind", "item")
        count = it.get("count", 1)
        no_quotes(it["name"], it.get("blurb", ""))
        atlas, sprite = icon(it["icon"])
        blurb = it.get("blurb", ENCHANT_TIP if kind == "enchant" else "")
        e = {"name": it["name"], "label": it["name"], "kind": kind, "count": count, "price": it["price"], "v2": it.get("v2", 0),
             "atlas": atlas, "sprite": sprite, "ncol": "white"}
        stack, bulk = 64, 0
        if kind == "item":
            e["item"] = item_string(it)
            stack, bulk = stack_size(it), 1
        elif kind == "enchant":
            e["ench"], e["lvl"] = it["ench"], it["lvl"]
        elif kind == "xp":
            e["lvl"], bulk = it["lvl"], 1
        else:
            raise SystemExit(f"{it['name']}: unknown kind {kind}")
        sl = max(1, stack // count) if kind == "item" else 8
        e.update(stack=stack, bulk=bulk, sl=sl)
        if "chat" in it:
            e["chat"] = it["chat"]
        n = 100 + len(self.items)
        self.items.append(e)
        unit = f"{count} for {it['price']}c" if bulk else ""
        return {"n": n, "label": it["name"], "ncol": "white", "atlas": atlas, "sprite": sprite, "price": it["price"],
                "count": count, "bulk": bulk, "sl": sl, "unit": nl(unit), "blurb": nl(blurb)}

    def section(self, sec, up, upg):
        """Node for a section (items, classes or a sub-menu); returns its index."""
        j = len(self.nodes)
        assert j <= 89, "too many shop screens (trigger codes 11..99)"
        self.nodes.append(None)
        node = {"name": sec["name"], "up": up, "upg": upg}
        if "sub" in sec:
            node["kind"] = "menu"
            buttons = [self.menu_button(s, self.section(s, j, k // PAGE)) for k, s in enumerate(sec["sub"])]
            node["pages"] = [buttons[i:i + PAGE] for i in range(0, len(buttons), PAGE)] or [[]]
        else:
            node["kind"] = "items"
            entries = [self.entry(it) for it in sec.get("items", [])]
            if sec.get("classes"):
                self.class_pages.append(j)
            node["pages"] = [entries[i:i + PAGE] for i in range(0, len(entries), PAGE)] or [[]]
        self.nodes[j] = node
        return j

    @staticmethod
    def menu_button(sec, j):
        atlas, sprite = icon(sec["icon"])
        no_quotes(sec["name"], sec.get("line", ""))
        tip = [{"text": sec["name"] + ("  ▸" if "sub" in sec else "") + "\n", "color": "gold"}]
        if sec.get("line"):
            tip.append({"text": "Shop Keeper: " + sec["line"], "color": "red", "italic": True})
        return {"label": [{"type": "object", "atlas": atlas, "sprite": sprite},
                          {"text": " " + sec["name"] + (" ▸" if "sub" in sec else ""), "color": "gold"}],
                "tooltip": tip, "width": WIDTH,
                "action": {"type": "minecraft:run_command", "command": f"trigger nx.shop set {10 + j}"}}

    def classes_entries(self):
        """Page entries for the Classes screen: the shop classes, at the indices class/gen/shop_items appends them to."""
        shop = [(cid, c) for cid, c in self.classes.items() if "shop" in c]
        gen = re.findall(r'"class": "([a-z_]+)"', SHOP_ITEMS.read_text(encoding="utf-8"))
        assert gen == [cid for cid, _ in shop], f"class/gen/shop_items is stale ({gen}): run tools/build_classes.py first"
        out = []
        for k, (cid, c) in enumerate(shop):
            no_quotes(c["name"]["text"], c.get("blurb", ""))
            out.append({"n": 100 + len(self.items) + k, "label": c["name"]["text"], "ncol": c["name"].get("color", "white"),
                        "atlas": c["shop"].get("atlas", "minecraft:items"), "sprite": c["shop"]["sprite"],
                        "price": c.get("price", 0), "count": 1, "bulk": 0, "sl": 1, "unit": "", "blurb": nl(c.get("blurb", ""))})
        return out

    def build(self, sections):
        top = [self.menu_button(s, self.section(s, 0, k // PAGE)) for k, s in enumerate(sections)]
        self.nodes[0] = {"name": "Shop", "up": 0, "upg": 0, "kind": "menu",
                         "pages": [top[i:i + PAGE] for i in range(0, len(top), PAGE)]}
        cls = self.classes_entries()
        for j in self.class_pages:
            self.nodes[j]["pages"] = [cls[i:i + PAGE] for i in range(0, len(cls), PAGE)] or [[]]
        return self


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--extra", type=Path, help="json with more sections (demo stress test), appended after src/shop.json's")
    ap.add_argument("--out", type=Path, default=OUT)
    a = ap.parse_args()
    sections = json.loads(SRC.read_text(encoding="utf-8"))["sections"]
    src = "src/shop.json"
    if a.extra:
        sections = sections + json.loads(a.extra.read_text(encoding="utf-8"))["sections"]
        src += " + " + a.extra.as_posix()
    b = Builder().build(sections)
    lines = [HEADER.format(src=src),
             "# Trigger nx.shop: 100 + i = buy items[i]; 10 + j = open nodes[j]; 1-10 = controls (shop/act).\n",
             "# The classes (class/gen/shop_items) are appended to items last.\n",
             "data modify storage nonios:shop items set value []\n"]
    lines += [f"data modify storage nonios:shop items append value {snbt(e)}\n" for e in b.items]
    lines += ["data modify storage nonios:shop nodes set value []\n"]
    lines += [f"data modify storage nonios:shop nodes append value {snbt(n)}\n" for n in b.nodes]
    lines += ["# + the classes sold here (generated from src/classes.json by tools/build_classes.py)\n",
              "function nonios:class/gen/shop_items\n"]
    out = a.out if a.out.is_absolute() else ROOT / a.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("".join(lines), encoding="utf-8", newline="\n")
    n_entries = sum(len(p) for n in b.nodes if n["kind"] == "items" for p in n["pages"])
    print(f"{out.relative_to(ROOT)}: {len(b.items)} items, {n_entries} buttons on {len(b.nodes)} screens")


if __name__ == "__main__":
    main()
