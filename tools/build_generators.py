"""Build the generator data from src/generators.json.

    python tools/build_generators.py                 # loot tables + grow/roll functions + config
    python tools/build_generators.py --structures    # also (re)import the V2.0 level structures (needs nbtlib)

Writes into datapack/data/nonios/:
  FIELD generators (mineable, V2 style; feedback #39):
  function/generator/grow/<team>_lvl<N>.mcfunction   one regrowth: 1 of 81 outcomes -> setblock at the generator
  loot_table/generator/jackpot_<id>.json             the V2 "chest" outcomes (the chest that grows is filled with it)
  loot_table/generator/one/<team>_lvl<N>.json        single-block mode (#47): the same 81 outcomes as one loot table
  tags/block/generator/single.json                   the single block (+ data/minecraft/loot_table/blocks/<it>.json emptied)
  function/generator/config.mcfunction               regrow delays, upgrade costs, single-block switch (runs on load)
  CENTRE generator (shared, pot style, in the arena):
  loot_table/arena/cgen_lvl<N>.json                  item outcomes
  function/arena/cgen/roll/lvl<N>.mcfunction         one roll: coins into the pot (emerald outcomes) or loot spawn
  function/arena/cgen/config.mcfunction              interval, bank scaling, pot caps (runs on load)
  structure/generator/<team>_lvl<N>.nbt              (--structures) V2 visuals; white is cropped from 5x5 to its 3x3 core
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "generators.json"
OUT = ROOT / "datapack" / "data" / "nonios"
# the original map sits next to Remaster/ (also when this runs from Remaster/.worktrees/<branch>); read-only
V2 = next((p / "V2.0 - Just substitute thee world" / "world" / "structures" for p in ROOT.parents
           if (p / "V2.0 - Just substitute thee world").is_dir()), None)
HEADER = "# GENERATED by tools/build_generators.py from src/generators.json - do not edit\n"


def item_entry(name, weight=None, count=1):
    e = {"type": "minecraft:item", "name": name}
    if weight is not None:
        e["weight"] = weight
    if count != 1:
        # 26.3 format: "modifier" (object or list) with "type"; the old "functions"/"function" keys are silently ignored
        e["modifier"] = {"type": "minecraft:set_count", "count": count}
    return e


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def ns(b):
    return b if ":" in b else "minecraft:" + b


def field(d):
    lt = OUT / "loot_table" / "generator"
    fn = OUT / "function" / "generator"
    # pot-style outputs from before feedback #39 are gone
    for old in list(lt.glob("white_lvl*.json")) + list(lt.glob("black_lvl*.json")) + list((fn / "roll").glob("*.mcfunction"))             + list(lt.glob("lucky_item.json")):
        old.unlink()
    if (fn / "roll").is_dir() and not any((fn / "roll").iterdir()):
        (fn / "roll").rmdir()
    for jid, j in d["jackpots"].items():
        # one pool per item so everything in the chest drops (a "group" entry only offers its children as alternatives)
        write(lt / f"jackpot_{jid}.json", json.dumps({
            "type": "minecraft:chest",
            "pools": [{"rolls": 1, "entries": [item_entry(n, count=c)]} for n, c in j["items"].items()]}, indent=1) + "\n")
    for team, levels in d["tables"].items():
        for lvl, outcomes in levels.items():
            total = sum(o[1] for o in outcomes)
            assert total == 81, f"{team} lvl{lvl}: outcomes sum to {total}, expected 81"
            lines = [HEADER, f"# {team} lvl{lvl}: as + at the generator marker (the block on top of the sea lantern). 1 of 81 outcomes.\n",
                     "execute store result score #r nx.gen run random value 1..81\n"]
            lo = 1
            for o in outcomes:
                name, w = o[0], o[1]
                hi = lo + w - 1
                if name == "coins":
                    block, what = ns(o[3]), f"{o[2]} emerald(s): pays through the purse when mined"
                elif name.startswith("jackpot:"):
                    block, what = f'minecraft:chest{{LootTable:"nonios:generator/jackpot_{name[8:]}"}}', "loot chest"
                else:
                    block = ns(o[2]) if len(o) > 2 and isinstance(o[2], str) else name
                    what = f"drops {name}"
                lines.append(f"# {w}/81 {what}\n")
                lines.append(f"execute if score #r nx.gen matches {lo}..{hi} run return run setblock ~ ~ ~ {block}\n")
                lo = hi + 1
            write(fn / "grow" / f"{team}_lvl{lvl}.mcfunction", "".join(lines))
    S = single(d)
    cfg = [HEADER, "# Runs on load. Per-level values are copied onto a generator when its level changes.\n",
           f"scoreboard players set #per_roll nx.gen {d['players_per_roll']}\n"]
    for lvl, v in d["levels"].items():
        cfg += [f"scoreboard players set #iv{lvl} nx.gen {v['regrow_ticks']}\n",
                f"scoreboard players set #cost{lvl} nx.gen {v['upgrade_cost']}\n"]
    blk = S["block"].split(":")[-1]
    cfg += ["# single-block mode (#47): default switch; the runtime switch (#single, generator/mode/toggle) wins once set\n",
            f"scoreboard players set #single_def nx.gen {1 if S['on'] else 0}\n",
            f"data modify storage nonios:gen single set value {{block:\"{ns(S['block'])}\"}}\n",
            "# who mined the single block (generator/one/mined)\n",
            f"scoreboard objectives add nx.gen_mn minecraft.mined:minecraft.{blk}\n"]
    write(fn / "config.mcfunction", "".join(cfg))


def single(d):
    """Single-block mode (feedback #47): per team/level, the V2 81-outcome table as one loot table (type fishing: the
    miner's tool is the context tool, so Fortune works). An outcome whose V2 block has a purse yield (src/yields.json)
    also drops a token (emerald with custom_data nx_yield:<block>) that generator/one/loot turns into that yield for
    the miner (it never reaches the ground)."""
    S = d["single"]
    yields = json.loads((ROOT / "src" / "yields.json").read_text(encoding="utf-8"))["blocks"]
    lt = OUT / "loot_table" / "generator" / "one"
    for team, levels in d["tables"].items():
        for lvl, outcomes in levels.items():
            entries = []
            for o in outcomes:
                name, w = o[0], o[1]
                if name == "coins":
                    block, item = ns(o[3]), None
                elif name.startswith("jackpot:"):
                    entries.append({"type": "minecraft:loot_table", "value": f"nonios:generator/jackpot_{name[8:]}", "weight": w})
                    continue
                else:
                    block = ns(o[2]) if len(o) > 2 and isinstance(o[2], str) else name
                    item = item_entry(name)
                    if block.endswith("_ore"):
                        item["modifier"] = {"type": "minecraft:apply_bonus", "enchantment": "minecraft:fortune", "formula": "minecraft:ore_drops"}
                b = block.split(":")[-1]
                pools = []
                if item:
                    pools.append({"rolls": 1, "entries": [item]})
                if b in yields:
                    pools.append({"rolls": 1, "entries": [{"type": "minecraft:item", "name": "minecraft:emerald", "modifier": {
                        "type": "minecraft:set_custom_data", "tag": {"nx_yield": b}}}]})
                if len(pools) == 1 and item:
                    item["weight"] = w
                    entries.append(item)
                else:
                    entries.append({"type": "minecraft:loot_table", "value": {"type": "minecraft:fishing", "pools": pools}, "weight": w})
            write(lt / f"{team}_lvl{lvl}.json", json.dumps({"type": "minecraft:fishing", "pools": [{"rolls": 1, "entries": entries}]}, indent=1) + "\n")
    blk = ns(S["block"])
    write(OUT / "tags" / "block" / "generator" / "single.json", json.dumps({"values": [blk]}) + "\n")
    # its own drop is the generator's loot (generator/one/mined); nothing else drops it (explosions, silk touch)
    write(ROOT / "datapack" / "data" / "minecraft" / "loot_table" / "blocks" / (blk.split(":")[1] + ".json"),
          json.dumps({"type": "minecraft:block", "pools": []}) + "\n")
    return S


def centre(d):
    c = d["centre"]
    lt = OUT / "loot_table" / "arena"
    fn = OUT / "function" / "arena" / "cgen"
    for lvl, outcomes in c["tables"].items():
        total = sum(o[1] for o in outcomes)
        assert total == 81, f"centre lvl{lvl}: outcomes sum to {total}, expected 81"
        entries = []
        lines = [HEADER, f"# centre lvl{lvl}: as + at the centre generator marker. Coin outcomes fill the pot, the rest drop items.\n",
                 "execute store result score #r nx.gen run random value 1..81\n"]
        lo = 1
        for o in outcomes:
            if o[0] == "coins":
                hi = lo + o[1] - 1
                lines.append(f"# {o[1]}/81 -> {o[2]} emerald(s) worth of coins\n")
                lines.append(f"execute if score #r nx.gen matches {lo}..{hi} run return run "
                             f"scoreboard players operation @s nx.gen_pot += #ce{o[2]} nx.gen\n")
                lo = hi + 1
            else:
                entries.append(item_entry(o[0], o[1], o[2] if len(o) > 2 else 1))
        lines.append(f"loot spawn ~ ~0.4 ~ loot nonios:arena/cgen_lvl{lvl}\n")
        write(lt / f"cgen_lvl{lvl}.json", json.dumps({"type": "minecraft:chest", "pools": [{"rolls": 1, "entries": entries}]}, indent=1) + "\n")
        write(fn / "roll" / f"lvl{lvl}.mcfunction", "".join(lines))
    ems = sorted({o[2] for t in c["tables"].values() for o in t if o[0] == "coins"})
    cfg = [HEADER, "# Runs on load (arena/load). Centre generator: interval, bank scaling, per-level pot cap + core item.\n"]
    cfg += [f"scoreboard players set #ce{e} nx.gen {e * c['emerald_coins']}\n" for e in ems]
    cfg += [f"scoreboard players set #cg_iv nx.gen {c['interval_ticks']}\n",
            f"scoreboard players set #cg_bpr nx.gen {c['bank_per_roll']}\n",
            f"scoreboard players set #cg_maxr nx.gen {c['max_rolls']}\n",
            f"scoreboard players set #cg_icap nx.gen {c['item_cap']}\n",
            f"scoreboard players set #cg_gold nx.gen {c['golden_speed']}\n"]
    for lvl, v in c["levels"].items():
        cfg += [f"scoreboard players set #cg_bank{lvl} nx.gen {v['bank']}\n",
                f"scoreboard players set #cg_cap{lvl} nx.gen {v['pot_cap']}\n",
                f"data modify storage nonios:gen ccore.l{lvl} set value \"{v['core']}\"\n"]
    write(fn / "config.mcfunction", "".join(cfg))


def build():
    d = json.loads(SRC.read_text(encoding="utf-8"))
    field(d)
    centre(d)
    print("generator data built")


def structures():
    import nbtlib
    from nbtlib.tag import Int, List, Compound
    dst = OUT / "structure" / "generator"
    dst.mkdir(parents=True, exist_ok=True)
    for lvl in (1, 2, 3):
        # black: a clean 3x3 (bedrock base, sea lantern, black glass) -> copy as is
        b = nbtlib.load(V2 / f"black_generator_lvl{lvl}.nbt")
        b.save(dst / f"black_lvl{lvl}.nbt")
        # white: 5x5 including the grass/dirt it was saved with -> keep the same 3x3 core (x,z 1..3)
        w = nbtlib.load(V2 / f"white_generator_lvl{lvl}.nbt")
        blocks = List[Compound]()
        for blk in w["blocks"]:
            x, y, z = (int(v) for v in blk["pos"])
            if 1 <= x <= 3 and 1 <= z <= 3:
                nb = Compound(blk)
                nb["pos"] = List[Int]([Int(x - 1), Int(y), Int(z - 1)])
                blocks.append(nb)
        w["blocks"] = blocks
        w["size"] = List[Int]([Int(3), Int(2), Int(3)])
        w.save(dst / f"white_lvl{lvl}.nbt")
    print("structures imported from", V2)


if __name__ == "__main__":
    build()
    if "--structures" in sys.argv:
        structures()
