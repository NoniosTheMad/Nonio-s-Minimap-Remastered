"""Build the arena node runes from src/runes.json (feedback #126).

    python tools/build_runes.py

Writes into datapack/data/nonios/function/arena/rune/gen/:
  <id>.mcfunction      macro {hot, hp, cold, cp}: the glyph as particles, as the viewer, positioned at the glyph centre and
                       rotated to face the viewer (^x = the viewer's right, ^y = up). Points 1..#lit nx.arena use `hot`
                       (particle + its "dx dy dz speed count"), the rest `cold`.
  <id>_tip.mcfunction  macro {tip}: one particle at point #tip nx.arena (the pen tip while the rune is being captured)
  defs.mcfunction      storage nonios:arena config.runes {<id>:{g,name,n}} and config.rune_of {<bonus>:<id>}
"""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "runes.json"
OUT = ROOT / "datapack" / "data" / "nonios" / "function" / "arena" / "rune" / "gen"
HEADER = "# GENERATED by tools/build_runes.py from src/runes.json - do not edit\n"


def sample(strokes, height, spacing):
    """Points along the strokes in drawing order, ~spacing blocks apart, centred on the glyph's middle."""
    pts = []
    for stroke in strokes:
        for i in range(len(stroke) - 1):
            (x0, y0), (x1, y1) = stroke[i], stroke[i + 1]
            x0, y0, x1, y1 = x0 * height, (y0 - 0.5) * height, x1 * height, (y1 - 0.5) * height
            n = max(1, round(math.hypot(x1 - x0, y1 - y0) / spacing))
            for k in range(n + 1):
                p = (x0 + (x1 - x0) * k / n, y0 + (y1 - y0) * k / n)
                # joints and branch roots: skip points that sit on one already drawn
                if any(math.hypot(p[0] - q[0], p[1] - q[1]) < spacing * 0.5 for q in pts):
                    continue
                pts.append(p)
    return pts


def f(v):
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def main():
    src = json.loads(SRC.read_text(encoding="utf-8"))
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.mcfunction"):
        old.unlink()
    defs, rune_of, total = [], [], {}
    for rid, r in src["runes"].items():
        pts = sample(r["strokes"], src["height"], src["spacing"])
        total[rid] = len(pts)
        body = [HEADER, f"# {r['name']} {r['glyph']}: {len(pts)} points\n"]
        tip = [HEADER, f"# {r['name']}: pen tip at point #tip nx.arena\n"]
        for i, (x, y) in enumerate(pts, 1):
            at = f"^{f(x)} ^{f(y)} ^"
            body.append(f"$execute if score #lit nx.arena matches {i}.. run particle $(hot) {at} $(hp) force @s\n")
            body.append(f"$execute if score #lit nx.arena matches ..{i - 1} run particle $(cold) {at} $(cp) force @s\n")
            tip.append(f"$execute if score #tip nx.arena matches {i} run return run particle $(tip) {at}0.1 0 0 0 0 1 force @s\n")
        (OUT / f"{rid}.mcfunction").write_text("".join(body), encoding="utf-8", newline="\n")
        (OUT / f"{rid}_tip.mcfunction").write_text("".join(tip), encoding="utf-8", newline="\n")
        defs.append(f'{rid}:{{g:"{r["glyph"]}",name:"{r["name"]}",n:{len(pts)}}}')
        rune_of.append(f'{r["bonus"]}:"{rid}"')
    (OUT / "defs.mcfunction").write_text(
        HEADER
        + "# runes: g = glyph character (bossbar, chat), name, n = particle points. rune_of: default rune of each node bonus.\n"
        + f"data modify storage nonios:arena config.runes set value {{{','.join(defs)}}}\n"
        + f"data modify storage nonios:arena config.rune_of set value {{{','.join(rune_of)}}}\n",
        encoding="utf-8", newline="\n")
    print("runes:", ", ".join(f"{k} {v} pts" for k, v in total.items()))


if __name__ == "__main__":
    main()
